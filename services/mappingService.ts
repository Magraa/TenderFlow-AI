/**
 * Mapping Service
 * Simplified service for managing procurement purpose mappings and Hindi transliteration.
 * 
 * Key features:
 * - Category-based purpose mappings (not item-based)
 * - AI transliteration API call once for unknown items, then reuse
 * - No complex phonetic engine needed
 */

const TEMPORARY_PURPOSE_HINDI = 'संबंधित कार्य हेतु आवश्यक सामग्री';
const TEMPORARY_PURPOSE_ENGLISH = 'Relevant work materials required';

// Export constants for testing
export { TEMPORARY_PURPOSE_HINDI, TEMPORARY_PURPOSE_ENGLISH };

/**
 * Get professional purpose by category
 * Falls back to temporary purpose if no mapping exists
 */
export async function getPurposeByCategory(category: string, language: 'hindi' | 'english' = 'hindi'): Promise<string> {
  try {
    const mapping = await dataService.purposeMappings.get(category, language);
    if (mapping) {
      // Increment usage count
      await dataService.purposeMappings.update(mapping.id, {
        usageCount: (mapping.usageCount || 0) + 1,
      });
      return mapping.professionalPurpose;
    }
    
    // No mapping found, return temporary purpose
    return language === 'hindi' ? TEMPORARY_PURPOSE_HINDI : TEMPORARY_PURPOSE_ENGLISH;
  } catch (error) {
    console.error('Error getting purpose by category:', error);
    return language === 'hindi' ? TEMPORARY_PURPOSE_HINDI : TEMPORARY_PURPOSE_ENGLISH;
  }
}

/**
 * Set professional purpose by category
 */
export async function setPurposeByCategory(
  category: string,
  purpose: string,
  language: 'hindi' | 'english' = 'hindi'
): Promise<void> {
  try {
    // Check if mapping already exists
    const existing = await dataService.purposeMappings.get(category, language);
    
    if (existing) {
      // Update existing mapping
      await dataService.purposeMappings.update(existing.id, {
        professionalPurpose: purpose,
        isAutoGenerated: false,
      });
    } else {
      // Create new mapping
      await dataService.purposeMappings.create({
        category,
        professionalPurpose: purpose,
        language,
        usageCount: 0,
        isAutoGenerated: false,
      });
    }
  } catch (error) {
    console.error('Error setting purpose by category:', error);
    throw error;
  }
}

