import { AILocationCache, LocalBodyType, PlaceMapping } from '@/types';
import { dataService } from '@/services/dataService';

export interface LocationSuggestion {
  place: PlaceMapping;
  score: number;
}

export interface AILocationResult {
  englishName: string;
  hindiName?: string;
  districtName: string;
  districtHindiName?: string;
  stateName: string;
  stateHindiName?: string;
  confidence: number;
  source: 'cache' | 'ai' | 'local';
}

