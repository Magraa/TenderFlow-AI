/**
 * Delete purpose mapping by category (deletes both language versions)
 */
export async function deletePurposeMapping(category: string): Promise<boolean> {
  try {
    // Delete both Hindi and English mappings for this category
    const hindiMapping = await dataService.purposeMappings.get(category, 'hindi');
    const englishMapping = await dataService.purposeMappings.get(category, 'english');
    
    let deleted = false;
    if (hindiMapping) {
      deleted = await dataService.purposeMappings.delete(hindiMapping.id);
    }
    if (englishMapping) {
      deleted = await dataService.purposeMappings.delete(englishMapping.id);
    }
    return deleted;
  } catch (error) {
    console.error('Error deleting purpose mapping:', error);
    return false;
  }
}

/**
 * Get Hindi name for an item
 * Calls AI transliteration API once for unknown items, then reuse
 */
export async function getHindiItemName(itemName: string): Promise<string> {
  try {
    const mapping = await dataService.itemHindiMappings.get(itemName);
    if (mapping) {
      // Increment usage count
      await dataService.itemHindiMappings.update(mapping.id, {
        usageCount: (mapping.usageCount || 0) + 1,
      });
      return mapping.hindiName;
    }
    
    // No mapping found, call AI transliteration API
    const hindiName = await transliterateToHindi(itemName);
    
    // Save the mapping for future use
    await dataService.itemHindiMappings.create({
      englishName: itemName,
      hindiName,
      type: 'item' as const,
      usageCount: 1,
      isAutoGenerated: true,
    });
    
    return hindiName;
  } catch (error) {
    console.error('Error getting Hindi item name:', error);
    return itemName; // Fallback to original name
  }
}

